"""Private, metadata-only music profile for periodic human/AI review.

Never exports Telegram file_id, file_unique_id, user/chat IDs, API keys,
media bytes, local paths or private source URLs. Not for a public Git repo.
"""
from __future__ import annotations

import argparse
import json
import os
from collections import defaultdict
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

from music_bot.storage import Library


def export_profile(
    db: Library, *, now: datetime | None = None, recent_days: int = 30,
    exposure_limit: int = 240,
) -> dict[str, Any]:
    """Snapshot the complete library plus weak provenance-labelled signals.

    A recent Telegram delivery is evidence of *sending*, never listening.
    Pre-upgrade uploads have added_at=None and are not falsely counted as
    recent imports.
    """
    if not 1 <= recent_days <= 365 or not 1 <= exposure_limit <= 2000:
        raise ValueError("Invalid export window")
    current = now or datetime.now(timezone.utc)
    if current.tzinfo is None:
        raise ValueError("now must contain timezone")
    current = current.astimezone(timezone.utc)
    cutoff = (current - timedelta(days=recent_days)).strftime("%Y-%m-%d %H:%M:%S")
    generated = current.isoformat(timespec="seconds").replace("+00:00", "Z")
    with db.con() as sql:
        sql.execute("BEGIN")
        tracks = sql.execute(
            "SELECT id, title, artist, added_at FROM tracks ORDER BY id"
        ).fetchall()
        ratings = {
            int(row["track_id"]): int(row["score"])
            for row in sql.execute("SELECT track_id,score FROM track_ratings")
        }
        dislikes = {
            int(row["track_id"]) for row in sql.execute("SELECT track_id FROM dislikes")
        }
        verdicts = {
            int(row["track_id"]): str(row["status"])
            for row in sql.execute("SELECT track_id,status FROM track_verdicts")
        }
        catalog_verdicts = [
            {"mbid": r["mbid"], "title": r["title"], "artist": r["artist"],
             "decision": r["status"], "updated_at_utc": r["updated_at"]}
            for r in sql.execute(
                """SELECT v.mbid,c.title,c.artist,v.status,v.updated_at
                   FROM catalog_verdicts v JOIN catalog_candidates c ON c.mbid=v.mbid
                   ORDER BY v.updated_at DESC,v.mbid"""
            )
        ]
        pl_rows = sql.execute(
            "SELECT id,name,kind FROM playlists ORDER BY id"
        ).fetchall()
        members: dict[int, list[int]] = defaultdict(list)
        liked: set[int] = set()
        kinds = {int(row["id"]): row["kind"] for row in pl_rows}
        for row in sql.execute(
            "SELECT playlist_id,track_id FROM playlist_tracks ORDER BY playlist_id,position"
        ):
            playlist_id, track_id = int(row["playlist_id"]), int(row["track_id"])
            members[playlist_id].append(track_id)
            if kinds.get(playlist_id) == "liked":
                liked.add(track_id)
        links = {
            int(row["track_id"]): {
                "recording_mbid": str(row["mbid"]),
                "identity_source": str(row["provenance"]),
            }
            for row in sql.execute(
                "SELECT track_id,mbid,provenance FROM track_recording_links"
            )
        }
        # Only a bounded exposure summary; no raw list of Telegram messages.
        exposure: dict[int, dict[str, Any]] = {}
        for row in sql.execute(
            "SELECT track_id,sent_at FROM sent_history ORDER BY id DESC LIMIT ?",
            (exposure_limit,),
        ):
            track_id = int(row["track_id"])
            if track_id not in exposure:
                exposure[track_id] = {
                    "recent_deliveries": 0, "last_delivered_at": row["sent_at"]
                }
            exposure[track_id]["recent_deliveries"] += 1
        # The explicit source is retained; automatic player telemetry is not
        # generated by Telegram's native player.
        feedback: dict[int, dict[str, int]] = defaultdict(
            lambda: {"manual_skips_30d": 0, "manual_finishes_30d": 0}
        )
        manual_cutoff = (current - timedelta(days=30)).strftime("%Y-%m-%d %H:%M:%S")
        for row in sql.execute(
            """SELECT track_id,event,COUNT(*) AS amount FROM playback_events
               WHERE source='manual' AND created_at>=?
               GROUP BY track_id,event""",
            (manual_cutoff,),
        ):
            key = "manual_skips_30d" if row["event"] == "skip" else "manual_finishes_30d"
            feedback[int(row["track_id"])][key] += int(row["amount"])
    exported_tracks: list[dict[str, Any]] = []
    new_ids: list[int] = []
    unknown_dates = 0
    for row in tracks:
        track_id = int(row["id"])
        added_at = row["added_at"]
        if added_at is None:
            unknown_dates += 1
        elif cutoff <= added_at <= current.strftime("%Y-%m-%d %H:%M:%S"):
            new_ids.append(track_id)
        exported_tracks.append({
            "id": track_id,
            "title": row["title"],
            "artist": row["artist"],
            "added_at_utc": added_at,
            "rating": ratings.get(track_id),
            "liked": track_id in liked,
            "disliked": track_id in dislikes,
            "decision": verdicts.get(track_id),
            **links.get(track_id, {}),
            **exposure.get(track_id, {"recent_deliveries": 0, "last_delivered_at": None}),
            **feedback.get(track_id, {"manual_skips_30d": 0, "manual_finishes_30d": 0}),
        })
    return {
        "schema_version": 1,
        "generated_at_utc": generated,
        "scope": "complete_music_library",
        "source": "private_owner_music_bot",
        "provenance": {
            "recent_deliveries": "Telegram messages sent, NOT verified listens",
            "manual_skips_30d": "explicit user-reported skips",
            "manual_finishes_30d": "explicit user-reported finishes",
            "added_at_utc": "first import timestamp if known, null for pre-upgrade tracks",
            "identity_source": "MusicBrainz identity confirmed by owner or imported media",
        },
        "recent_days": recent_days,
        "recent_cutoff_utc": cutoff.replace(" ", "T") + "Z",
        "unknown_addition_dates": unknown_dates,
        "total_tracks": len(exported_tracks),
        "recently_added_track_ids": new_ids,
        "tracks": exported_tracks,
        "catalog_decisions": catalog_verdicts,
        "playlists": [
            {
                "id": int(p["id"]), "name": p["name"], "kind": p["kind"],
                "track_ids_in_order": members[int(p["id"])],
            }
            for p in pl_rows
        ],
    }


def profile_json_bytes(snapshot: dict[str, Any]) -> bytes:
    return (json.dumps(snapshot, ensure_ascii=False, indent=2, sort_keys=True)
            + "\n").encode("utf-8")


def compare_profiles(previous: dict[str, Any], current: dict[str, Any]) -> dict:
    """Detect additions and changed signals even when old upload dates are unknown.

    Both snapshots must be from the same bot database; numeric track IDs are
    local identifiers, not globally unique MusicBrainz identifiers.
    """
    if previous.get("schema_version") != 1 or current.get("schema_version") != 1:
        raise ValueError("Unsupported music profile snapshot schema")
    if previous.get("scope") != "complete_music_library" or current.get("scope") != "complete_music_library":
        raise ValueError("Only comparable full library exports are supported")
    old = {int(row["id"]): row for row in previous["tracks"]}
    new = {int(row["id"]): row for row in current["tracks"]}
    created_ids = sorted(new.keys() - old.keys())
    deleted_ids = sorted(old.keys() - new.keys())
    rating_changes = [
        {"id": tid, "before": old[tid].get("rating"), "after": new[tid].get("rating")}
        for tid in sorted(old.keys() & new.keys())
        if old[tid].get("rating") != new[tid].get("rating")
    ]
    newly_liked = [
        tid for tid in sorted(old.keys() & new.keys())
        if not old[tid].get("liked") and new[tid].get("liked")
    ]
    decision_changes = [
        {"id": tid, "before": old[tid].get("decision"), "after": new[tid].get("decision")}
        for tid in sorted(old.keys() & new.keys())
        if old[tid].get("decision") != new[tid].get("decision")
    ]
    old_catalog = {
        record["mbid"]: record["decision"]
        for record in previous.get("catalog_decisions", [])
    }
    catalog_decision_changes = [
        {"mbid": record["mbid"], "artist": record["artist"],
         "title": record["title"], "before": old_catalog.get(record["mbid"]),
         "after": record["decision"]}
        for record in current.get("catalog_decisions", [])
        if old_catalog.get(record["mbid"]) != record["decision"]
    ]
    old_lists = {
        int(pl["id"]): set(pl["track_ids_in_order"])
        for pl in previous.get("playlists", [])
    }
    playlist_additions = [
        {
            "playlist_id": int(pl["id"]),
            "playlist_name": pl["name"],
            "added_track_ids": [
                int(tid) for tid in pl["track_ids_in_order"]
                if tid not in old_lists.get(int(pl["id"]), set())
            ],
        }
        for pl in current.get("playlists", []) if pl.get("kind") == "custom"
    ]
    playlist_additions = [
        item for item in playlist_additions if item["added_track_ids"]
    ]
    return {
        "from": previous.get("generated_at_utc"),
        "to": current.get("generated_at_utc"),
        "new_tracks": [new[tid] for tid in created_ids],
        "removed_track_ids": deleted_ids,
        "rating_changes": rating_changes,
        "newly_liked_track_ids": newly_liked,
        "decision_changes": decision_changes,
        "catalog_decision_changes": catalog_decision_changes,
        "playlist_additions": playlist_additions,
        "warning": "Compare only snapshots of the same music bot database",
    }


def write_private_export(path: str | Path, content: bytes) -> Path:
    """Write with 0600 permissions, never overwrite or follow a file symlink."""
    dest = Path(path)
    dest.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    fd = os.open(dest, flags, 0o600)
    with os.fdopen(fd, "wb") as out:
        out.write(content)
    return dest


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Private music taste snapshot")
    parser.add_argument("--database", default="data/music.db")
    parser.add_argument("--output", required=True,
                        help="Local JSON destination outside the public repository")
    parser.add_argument("--recent-days", type=int, default=30)
    parser.add_argument("--compare", help="Optional previous snapshot to compare")
    args = parser.parse_args(argv)
    if not Path(args.database).is_file():
        parser.error("The music database does not exist")
    snapshot = export_profile(
        Library(args.database), recent_days=args.recent_days,
    )
    target = write_private_export(args.output, profile_json_bytes(snapshot))
    print(f"Private music snapshot saved: {target}")
    print(f"Tracks: {snapshot['total_tracks']}, recently imported: "
          f"{len(snapshot['recently_added_track_ids'])}, "
          f"unknown old dates: {snapshot['unknown_addition_dates']}")
    if args.compare:
        previous = json.loads(Path(args.compare).read_text(encoding="utf-8"))
        change = compare_profiles(previous, snapshot)
        print(f"Since previous export: {len(change['new_tracks'])} new, "
              f"{len(change['rating_changes'])} changed ratings, "
              f"{len(change['newly_liked_track_ids'])} newly liked.")
    print("Private taste data: do NOT commit to the public music repository.")


if __name__ == "__main__":
    main()
